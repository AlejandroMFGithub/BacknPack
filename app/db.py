def now_text():
    """Marca de tiempo UTC con el mismo formato que CURRENT_TIMESTAMP de SQLite."""
    return datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S")


def is_postgres_url(url):
    return str(url).startswith(("postgres://", "postgresql://"))


def to_postgres_ddl(sql):
    """Traduce el DDL escrito para SQLite a PostgreSQL."""
    sql = sql.replace("INTEGER PRIMARY KEY AUTOINCREMENT", "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY")
    sql = sql.replace(
        "DEFAULT CURRENT_TIMESTAMP", "DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')"
    )
    sql = re.sub(r"\bREAL\b", "DOUBLE PRECISION", sql)
    return re.sub(r"\bBLOB\b", "BYTEA", sql)


class PgRow(tuple):
    """Fila de PostgreSQL que, como sqlite3.Row, admite row['col'], row[0] y keys()."""

    def __new__(cls, values, index):
        row = super().__new__(cls, values)
        row._index = index
        return row

    def __getitem__(self, key):
        if isinstance(key, str):
            return tuple.__getitem__(self, self._index[key])
        return tuple.__getitem__(self, key)

    def keys(self):
        return list(self._index)


def _pg_row_factory(cursor):
    index = {col.name: i for i, col in enumerate(cursor.description or [])}
    return lambda values: PgRow(values, index)


class Database:
    def __init__(self, target):
        self.is_postgres = is_postgres_url(target)
        if self.is_postgres:
            import psycopg  # solo hace falta en producción
            # prepare_threshold=None: compatible con el pooler de Neon (PgBouncer)
            self.conn = psycopg.connect(target, row_factory=_pg_row_factory, prepare_threshold=None)
        else:
            self.conn = sqlite3.connect(target)
            self.conn.row_factory = sqlite3.Row
            self.conn.execute("PRAGMA foreign_keys = ON")

    def _sql(self, sql):
        return sql.replace("?", "%s") if self.is_postgres else sql

    def execute(self, sql, params=()):
        return self.conn.execute(self._sql(sql), params)

    def insert(self, sql, params=()):
        """Ejecuta un INSERT y devuelve el id de la fila creada."""
        if self.is_postgres:
            return self.conn.execute(self._sql(sql) + " RETURNING id", params).fetchone()[0]
        return self.conn.execute(sql, params).lastrowid

    def script(self, sql):
        """Ejecuta varias sentencias DDL seguidas."""
        if self.is_postgres:
            self.conn.execute(to_postgres_ddl(sql))
        else:
            self.conn.executescript(sql)

    def begin(self):
        """Abre una transacción de escritura exclusiva: compras, botín e intercambios
        se ejecutan de uno en uno para que nadie gaste dos veces la misma moneda."""
        if self.is_postgres:
            self.conn.execute("SELECT pg_advisory_xact_lock(4242)")
        elif not self.conn.in_transaction:
            self.conn.execute("BEGIN IMMEDIATE")

    def commit(self):
        self.conn.commit()

    def rollback(self):
        self.conn.rollback()

    def close(self):
        self.conn.close()

    # --- Esquema --------------------------------------------------------------------

    def has_schema(self):
        if self.is_postgres:
            return self.execute("SELECT to_regclass('public.users') IS NOT NULL").fetchone()[0]
        return self.execute(
            "SELECT 1 FROM sqlite_master WHERE type = 'table' AND name = 'users'"
        ).fetchone() is not None

    def get_version(self):
        if not self.is_postgres:
            return self.execute("PRAGMA user_version").fetchone()[0]
        self.execute("CREATE TABLE IF NOT EXISTS schema_version (version INTEGER NOT NULL)")
        row = self.execute("SELECT version FROM schema_version").fetchone()
        return row[0] if row else 0

    def set_version(self, version):
        if not self.is_postgres:
            self.execute(f"PRAGMA user_version = {int(version)}")
            return
        self.execute("CREATE TABLE IF NOT EXISTS schema_version (version INTEGER NOT NULL)")
        self.execute("DELETE FROM schema_version")
        self.execute("INSERT INTO schema_version (version) VALUES (?)", (version,))

    def create_schema(self):
        """Borra y crea todas las tablas en su versión más reciente."""
        with current_app.open_resource("schema.sql") as f:
            self.script(f.read().decode("utf-8"))
        self.set_version(0)
        migrate(self)


def get_db():
    if "db" not in g:
        g.db = Database(current_app.config["DATABASE"])
    return g.db


def close_db(e=None):
    db = g.pop("db", None)
    if db is not None:
        db.close()


@contextmanager
def transaction():
    """Agrupa varias operaciones en una transacción atómica (todo o nada)."""
    db = get_db()
    db.begin()
    try:
        yield db
        db.commit()
    except Exception:
        db.rollback()
        raise


def init_db(demo=True):
    dm_password = _initial_dm_password(demo)  # antes de tocar nada: si falta, no se crea nada
    db = get_db()
    db.create_schema()
    from .seed import seed
    seed(demo=demo, dm_password=dm_password)


def _initial_dm_password(demo):
    password = current_app.config.get("DM_PASSWORD")
    if password:
        return password
    if demo:
        return "dm"
    raise RuntimeError(
        "Falta la variable de entorno DM_PASSWORD con la contraseña inicial del DM."
    )


# --- Comandos de consola -------------------------------------------------------------

@click.command("init-db")
@with_appcontext
@click.option("--no-demo", is_flag=True, help="Solo crea el DM, las divisas y el catálogo básico.")
@click.confirmation_option(prompt="Se BORRARÁN todos los datos de la base de datos. ¿Seguro?")
def init_db_command(no_demo):
    """Borra y recrea la base de datos."""
    init_db(demo=not no_demo and not get_db().is_postgres)
    click.echo("Base de datos inicializada.")


@click.command("copy-to-postgres")
@with_appcontext
@click.option("--source", default=None, help="Fichero SQLite de origen (por defecto instance/backnpack.sqlite).")
@click.option("--exclude-users", default="", help="Usuarios que NO se copian (con sus personajes), separados por comas.")
@click.confirmation_option(prompt="Se BORRARÁ todo lo que haya en la base de datos de DATABASE_URL. ¿Seguro?")
def copy_to_postgres_command(source, exclude_users):
    """Copia todos los datos de la SQLite local a la PostgreSQL de DATABASE_URL."""
    if not is_postgres_url(current_app.config["DATABASE"]):
        raise click.ClickException("Define DATABASE_URL con la cadena de conexión de Neon.")
    source = source or os.path.join(current_app.instance_path, "backnpack.sqlite")
    if not os.path.exists(source):
        raise click.ClickException(f"No existe {source}")

    src = Database(source)
    migrate(src)
    dst = get_db()  # la app ya apunta a DATABASE_URL
    dst.create_schema()

    for table in TABLES:
        rows = src.execute(f"SELECT * FROM {table}").fetchall()
        if not rows:
            continue
        cols = rows[0].keys()
        sql = f"INSERT INTO {table} ({', '.join(cols)}) VALUES ({', '.join('%s' for _ in cols)})"
        with dst.conn.cursor() as cur:
            cur.executemany(sql, [tuple(r) for r in rows])
        if "id" in cols:
            dst.execute(
                f"SELECT setval(pg_get_serial_sequence('{table}', 'id'), "
                f"(SELECT COALESCE(MAX(id), 0) + 1 FROM {table}), false)"
            )
        click.echo(f"  {table}: {len(rows)} filas")

    excluded = [u.strip() for u in exclude_users.split(",") if u.strip()]
    for username in excluded:
        dst.execute("DELETE FROM users WHERE username = ?", (username,))
        click.echo(f"  usuario excluido: {username}")

    if current_app.config.get("DM_PASSWORD"):
        from werkzeug.security import generate_password_hash
        dst.execute(
            "UPDATE users SET password_hash = ? WHERE role = 'dm'",
            (generate_password_hash(current_app.config["DM_PASSWORD"]),),
        )
        click.echo("  contraseña del DM actualizada con DM_PASSWORD")
    dst.commit()
    src.close()
    click.echo("Copia terminada.")


def init_app(app):
    app.teardown_appcontext(close_db)
    app.cli.add_command(init_db_command)
    app.cli.add_command(copy_to_postgres_command)
    with app.app_context():
        db = get_db()
        # Sin usuarios = nunca se terminó de inicializar (p. ej. un primer arranque fallido)
        if db.has_schema() and db.execute("SELECT COUNT(*) FROM users").fetchone()[0] > 0:
            migrate(db)
        else:
            # Los datos de ejemplo (con cuentas ana/ana…) solo en SQLite local
            demo = app.config.get("DEMO_DATA")
            if demo is None:
                demo = not db.is_postgres and not app.config["PRODUCTION"]
            init_db(demo=demo)
